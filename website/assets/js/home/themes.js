export function customTheme({ hue, tint, depth, contrast, accent, light }) {
  const s = tint * .5;
  const step = .5 + contrast / 100;
  const base = light ? 80 + depth * .12 : 2 + depth * .12;
  const layer = n => `hsl(${hue} ${s}% ${Math.min(99, base + n * step)}%)`;
  const ink = l => `hsl(${hue} ${Math.min(s, 22)}% ${l}%)`;
  return {
    '--bg-app': layer(0), '--bg-island': layer(light ? 9 : 4.5),
    '--bg-raised': layer(light ? 5 : 8), '--bg-input': light ? '#fff' : layer(8),
    '--bg-active': `color-mix(in srgb, ${accent} ${light ? 18 : 24}%, ${layer(light ? 9 : 4.5)})`,
    '--line': `hsl(${hue} 30% ${light ? 20 : 92}% / ${light ? .09 : .06})`,
    '--line-strong': `hsl(${hue} 30% ${light ? 20 : 92}% / ${light ? .16 : .12})`,
    '--text': ink(light ? 11 : 94), '--text-2': ink(light ? 27 : 82),
    '--muted': ink(light ? 45 : 63), '--faint': ink(light ? 62 : 46),
    '--accent': accent, '--accent-2': `color-mix(in srgb, ${accent}, white 30%)`,
  };
}
